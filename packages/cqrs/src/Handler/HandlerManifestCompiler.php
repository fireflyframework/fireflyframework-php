<?php

declare(strict_types=1);

namespace Firefly\Cqrs\Handler;

use Firefly\Cqrs\Cache\CachedQueryPolicy;
use Firefly\Cqrs\Cache\InvalidationRule;
use Firefly\Kernel\Exception\Framework\ConfigurationException;

/**
 * Mirrors the ScheduledManifestCompiler: var_export of the handler rows + the destinations map into a require-able
 * PHP file with two top-level keys. Run Pint after any regen (the compiler emits raw var_export style). The cache
 * sections are trailing optional arguments so the 3-argument write() every existing caller uses keeps compiling.
 *
 * @phpstan-import-type HandlerRow from HandlerDescriptor
 * @phpstan-import-type CachedQueryRow from CachedQueryPolicy
 * @phpstan-import-type InvalidationRow from InvalidationRule
 */
final class HandlerManifestCompiler
{
    /**
     * @param  list<HandlerDescriptor>  $handlers
     * @param  array<string,string>  $destinations
     * @param  array<string, CachedQueryPolicy>  $cachedQueries
     * @param  list<InvalidationRule>  $invalidations
     */
    public function compile(array $handlers, array $destinations, array $cachedQueries = [], array $invalidations = []): string
    {
        return "<?php\n\ndeclare(strict_types=1);\n\n// Generated by firefly/cqrs. Do not edit.\n\nreturn "
            .var_export($this->toArray($handlers, $destinations, $cachedQueries, $invalidations), true)
            .";\n";
    }

    /**
     * @param  list<HandlerDescriptor>  $handlers
     * @param  array<string,string>  $destinations
     * @param  array<string, CachedQueryPolicy>  $cachedQueries
     * @param  list<InvalidationRule>  $invalidations
     * @return array{handlers: list<HandlerRow>, destinations: array<string,string>, cachedQueries: array<string, CachedQueryRow>, invalidations: list<InvalidationRow>}
     */
    public function toArray(array $handlers, array $destinations, array $cachedQueries = [], array $invalidations = []): array
    {
        return [
            'handlers' => array_map(static fn (HandlerDescriptor $h): array => $h->toArray(), $handlers),
            'destinations' => $destinations,
            'cachedQueries' => array_map(static fn (CachedQueryPolicy $p): array => $p->toArray(), $cachedQueries),
            'invalidations' => array_map(static fn (InvalidationRule $r): array => $r->toArray(), $invalidations),
        ];
    }

    /**
     * @param  list<HandlerDescriptor>  $handlers
     * @param  array<string,string>  $destinations
     * @param  array<string, CachedQueryPolicy>  $cachedQueries
     * @param  list<InvalidationRule>  $invalidations
     */
    public function write(array $handlers, array $destinations, string $path, array $cachedQueries = [], array $invalidations = []): void
    {
        $dir = dirname($path);
        if (! is_dir($dir) && ! mkdir($dir, 0o775, true) && ! is_dir($dir)) {
            throw new ConfigurationException("Could not create manifest directory {$dir}.");
        }

        if (file_put_contents($path, $this->compile($handlers, $destinations, $cachedQueries, $invalidations)) === false) {
            throw new ConfigurationException("Could not write handler manifest to {$path}.");
        }
    }
}
