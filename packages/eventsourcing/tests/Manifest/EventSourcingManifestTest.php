<?php

declare(strict_types=1);

use Firefly\EventSourcing\Event\EventParameter;
use Firefly\EventSourcing\Manifest\EventSourcingManifest;
use Firefly\EventSourcing\Manifest\EventSourcingManifestCompiler;
use Firefly\EventSourcing\Scanner\EventSourcingScanner;
use Firefly\EventSourcing\Tests\Fixtures\Events\OrderChannel;
use Firefly\EventSourcing\Tests\Fixtures\Events\OrderPaid;
use Firefly\EventSourcing\Tests\Fixtures\Events\OrderPlaced;
use Firefly\Kernel\Exception\Framework\ConfigurationException;

/** @return array<string, string> */
function eventFixtures(string $dir = 'Fixtures/Events', string $namespace = 'Fixtures\\Events'): array
{
    return ['Firefly\\EventSourcing\\Tests\\'.$namespace.'\\' => dirname(__DIR__).'/'.$dir];
}

it('scans #[EventType] events with their constructor parameters, and compiles them to a file that loads back', function (): void {
    $manifest = (new EventSourcingScanner)->scan(eventFixtures());
    $path = sys_get_temp_dir().'/firefly-eventsourcing-manifest-'.bin2hex(random_bytes(6)).'.php';

    try {
        (new EventSourcingManifestCompiler)->write($manifest, $path);
        $loaded = EventSourcingManifest::load($path);
        $byType = [];
        foreach ($loaded->eventTypes() as $descriptor) {
            $byType[$descriptor->type] = $descriptor;
        }

        expect((string) file_get_contents($path))->toStartWith("<?php\n\ndeclare(strict_types=1);\n\n// Generated by firefly/eventsourcing. Do not edit.")
            ->and($loaded->toArray())->toBe($manifest->toArray())
            ->and(array_keys($byType))->toBe(['order.paid', 'order.placed'])
            ->and([$byType['order.placed']->class, $byType['order.placed']->version, $byType['order.placed']->serializable])->toBe([OrderPlaced::class, 2, false])
            ->and($byType['order.placed']->parameters)->toEqual([
                new EventParameter('orderId', 'string', false, false),
                new EventParameter('total', 'float', false, false),
                new EventParameter('channel', OrderChannel::class, false, true),
                new EventParameter('promisedBy', DateTimeImmutable::class, true, true),
                new EventParameter('skus', 'array', false, true),
                new EventParameter('eventId', 'string', true, true),
                new EventParameter('occurredAt', DateTimeImmutable::class, true, true),
            ])
            ->and([$byType['order.paid']->class, $byType['order.paid']->serializable, $byType['order.paid']->parameters])->toBe([OrderPaid::class, true, []])
            ->and(EventSourcingManifest::empty()->isEmpty())->toBeTrue();
    } finally {
        @unlink($path);
    }
});

it('refuses #[EventType] on a class that is not a DomainEvent, and one type named twice', function (string $dir, string $namespace, string $message): void {
    expect(fn () => (new EventSourcingScanner)->scan(eventFixtures($dir, $namespace)))->toThrow(ConfigurationException::class, $message);
})->with([
    'not a domain event' => ['InvalidFixtures/NotADomainEvent', 'InvalidFixtures\\NotADomainEvent', 'must extend Firefly\\Domain\\DomainEvent'],
    'duplicate type' => ['InvalidFixtures/DuplicateType', 'InvalidFixtures\\DuplicateType', 'twice.named'],
]);

it('refuses a convention-mapped event whose constructor parameters and public properties do not match, pointing to SerializableEvent', function (string $dir, string $namespace, string $message): void {
    expect(fn () => (new EventSourcingScanner)->scan(eventFixtures($dir, $namespace)))
        ->toThrow(ConfigurationException::class, $message)
        ->and(fn () => (new EventSourcingScanner)->scan(eventFixtures($dir, $namespace)))
        ->toThrow(ConfigurationException::class, 'implement Firefly\\EventSourcing\\Event\\SerializableEvent');
})->with([
    'a parameter with no public property' => ['InvalidFixtures/UnstoredParameter', 'InvalidFixtures\\UnstoredParameter', 'the constructor parameter(s) $id have no public property of the same name'],
    'a public property no parameter takes' => ['InvalidFixtures/UnreadProperty', 'InvalidFixtures\\UnreadProperty', 'the public property(ies) $qty are not constructor parameters'],
]);

it('refuses a convention-mapped constructor parameter whose type the mapper cannot rebuild, naming it and pointing to SerializableEvent', function (): void {
    $scan = fn () => (new EventSourcingScanner)->scan(eventFixtures('InvalidFixtures/UnbuildableType', 'InvalidFixtures\\UnbuildableType'));

    expect($scan)->toThrow(ConfigurationException::class, 'the constructor parameter(s) $price (Firefly\\EventSourcing\\Tests\\InvalidFixtures\\UnbuildableType\\Money) have a type the convention mapper cannot rebuild')
        ->and($scan)->toThrow(ConfigurationException::class, 'implement Firefly\\EventSourcing\\Event\\SerializableEvent');
});
