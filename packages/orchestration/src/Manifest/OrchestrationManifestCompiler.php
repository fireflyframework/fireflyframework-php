<?php

declare(strict_types=1);

namespace Firefly\Orchestration\Manifest;

use Firefly\Kernel\Exception\Framework\ConfigurationException;

/** var_export of the manifest rows into a require-able PHP file (the ScheduledManifestCompiler shape). */
final class OrchestrationManifestCompiler
{
    public function compile(OrchestrationManifest $manifest): string
    {
        return "<?php\n\ndeclare(strict_types=1);\n\n// Generated by firefly/orchestration. Do not edit.\n\nreturn "
            .var_export($manifest->toArray(), true)
            .";\n";
    }

    public function write(OrchestrationManifest $manifest, string $path): void
    {
        $dir = dirname($path);
        if (! is_dir($dir) && ! mkdir($dir, 0o775, true) && ! is_dir($dir)) {
            throw new ConfigurationException("Could not create manifest directory {$dir}.");
        }

        if (file_put_contents($path, $this->compile($manifest)) === false) {
            throw new ConfigurationException("Could not write the orchestration manifest to {$path}.");
        }
    }
}
