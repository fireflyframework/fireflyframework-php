<?php

declare(strict_types=1);

use Firefly\Orchestration\Manifest\OrchestrationManifest;
use Firefly\Orchestration\Manifest\OrchestrationManifestCompiler;
use Firefly\Orchestration\Scanner\OrchestrationScanner;

it('compiles to a require-able file that loads back to the same definitions', function (): void {
    $manifest = (new OrchestrationScanner)->scan(['Firefly\\Orchestration\\Tests\\ScannerFixtures\\Good\\' => dirname(__DIR__).'/ScannerFixtures/Good']);
    $path = sys_get_temp_dir().'/firefly-orchestration-manifest-'.bin2hex(random_bytes(6)).'.php';

    try {
        (new OrchestrationManifestCompiler)->write($manifest, $path);
        $loaded = OrchestrationManifest::load($path);

        expect((string) file_get_contents($path))->toStartWith("<?php\n\ndeclare(strict_types=1);\n\n// Generated by firefly/orchestration. Do not edit.")
            ->and($loaded->toArray())->toBe($manifest->toArray())
            ->and($loaded->sagas())->toEqual($manifest->sagas())
            ->and($loaded->workflows())->toEqual($manifest->workflows())
            ->and(OrchestrationManifest::empty()->isEmpty())->toBeTrue()
            ->and($loaded->isEmpty())->toBeFalse();
    } finally {
        @unlink($path);
    }
});
